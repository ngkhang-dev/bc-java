package model;

public class Pair<K, V> {
    private K key;
    private V value;

    public Pair(K key, V value) {
        this.key = key;
        this.value = value;
    }

    public K getKey() {
        return key;
    }

    public void setKey(K key) {
        this.key = key;
    }

    public V getValue() {
        return value;
    }

    public void setValue(V value) {
        this.value = value;
    }

    @Override
    public String toString() {
        return "Pair: Type key= " + key.getClass().getSimpleName() + ", Type value= " + value.getClass().getSimpleName();
    }

    public void display() {
        System.out.println(toString());
    }
}
